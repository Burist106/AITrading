export function getScenario(
  id: PrototypeScenarioId = scenarioStore.defaultScenarioId,
): ScenarioPresentation {
  return (
    scenarioStore.scenarios.find((candidate) => candidate.id === id) ??
    scenarioStore.scenarios[0]!
  );
}

export function getSample(scenarioId: PrototypeScenarioId): ScenarioSample {
  const selected = getScenario(scenarioId);
  return scenarioStore.samples[selected.sampleRef];
}
